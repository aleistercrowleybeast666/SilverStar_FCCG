def _ResourceHeader_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    result = ResourceAssignments_Resolve(model, catalog)
    if not result.valid:
        raise ValueError("Cannot generate resource header: " + "; ".join(result.errors))
    includes = set()
    lines: list[str] = []
    for assignment in result.assignments:
        macro = assignment.requirement.binding_macro
        if not macro:
            continue
        header = assignment.provision.metadata.get("header")
        if isinstance(header, str) and header:
            includes.add(header)
        c_id = assignment.provision.metadata.get("c_id", assignment.provision.resource_id)
        lines.append(f"#define {macro:<42} {c_id}")
    include_text = "\n".join(f'#include "{header}"' for header in sorted(includes))
    define_text = "\n".join(lines)
    return f"""#ifndef __PROJECT_RESOURCES_H
#define __PROJECT_RESOURCES_H

{AUTOGEN_C_COMMENT}

{include_text}

{define_text}

#endif /* __PROJECT_RESOURCES_H */
"""


def _PlatformResources_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    if model.hardware.mode == "custom":
        platform = _CustomPlatformResources_Get(model)
    else:
        board = catalog.Component_Get(model.board)
        platform = board.metadata.get("platform_resources", {})
    uarts = platform.get("uarts", [])
    spis = platform.get("spis", [])
    adcs = platform.get("adcs", [])
    gpios = platform.get("gpios", [])
    uart_values = ",\n".join(
        f"    [PLATFORM_UART_{index + 1}] = &{entry['handle']}"
        for index, entry in enumerate(uarts[:3])
    )
    spi_values = ",\n".join(
        f"    [PLATFORM_SPI_{index + 1}] = &{entry['handle']}"
        for index, entry in enumerate(spis[:1])
    )
    adc_values = ",\n".join(
        f"    [PLATFORM_ADC_{index + 1}] = &{entry['handle']}"
        for index, entry in enumerate(adcs[:1])
    )
    gpio_values = ",\n".join(
        f"    [PLATFORM_GPIO_{index}] = "
        f"{{{entry['port']}, {entry['pin']}, "
        f"{int(entry.get('irq_enabled', entry.get('active_high', 0)))}U}}"
        for index, entry in enumerate(gpios[:9])
    )
    return f"""#include "platform_stm32f4_resources.h"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

#include "adc.h"
#include "main.h"
#include "spi.h"
#include "usart.h"

static void * const s_uart_handles[PLATFORM_UART_COUNT] =
{{
{uart_values}
}};

static void * const s_spi_handles[PLATFORM_SPI_COUNT] =
{{
{spi_values}
}};

static void * const s_adc_handles[PLATFORM_ADC_COUNT] =
{{
{adc_values}
}};

static const PlatformStm32f4GpioResource
    s_gpio_resources[PLATFORM_GPIO_COUNT] =
{{
{gpio_values}
}};

void *PlatformStm32f4Resource_UartHandleGet(PlatformUartId id)
{{
    return ((uint32_t)id < (uint32_t)PLATFORM_UART_COUNT) ?
        s_uart_handles[id] : NULL;
}}

void *PlatformStm32f4Resource_SpiHandleGet(PlatformSpiId id)
{{
    return ((uint32_t)id < (uint32_t)PLATFORM_SPI_COUNT) ?
        s_spi_handles[id] : NULL;
}}

void *PlatformStm32f4Resource_AdcHandleGet(PlatformAdcId id)
{{
    return ((uint32_t)id < (uint32_t)PLATFORM_ADC_COUNT) ?
        s_adc_handles[id] : NULL;
}}

uint8_t PlatformStm32f4Resource_GpioGet(
    PlatformGpioId id,
    PlatformStm32f4GpioResource *resource)
{{
    if (((uint32_t)id >= (uint32_t)PLATFORM_GPIO_COUNT) ||
        (resource == NULL))
    {{
        return 0U;
    }}
    *resource = s_gpio_resources[id];
    return 1U;
}}
"""


def _CustomPlatformResources_Get(model: ProjectModel) -> dict[str, list[dict[str, Any]]]:
    platform: dict[str, list[dict[str, Any]]] = {
        "uarts": [],
        "spis": [],
        "adcs": [],
        "gpios": [],
    }
    destinations = {"uart": "uarts", "spi": "spis", "adc": "adcs"}
    for resource in model.hardware.resources:
        metadata = resource.metadata
        destination = destinations.get(resource.kind)
        if destination is not None and isinstance(metadata.get("handle"), str):
            platform[destination].append({"id": resource.resource_id, **metadata})
        elif resource.kind.startswith("gpio_") and isinstance(metadata.get("port"), str):
            platform["gpios"].append({"id": resource.resource_id, **metadata})
    for values in platform.values():
        values.sort(key=lambda entry: int(entry.get("logical_index", 0)))
    return platform


def _LogSource_Render(model: ProjectModel) -> str:
    rows = []
    for stream in model.logging_streams:
        rows.append(
            f"    {{{stream.record}, {1 if stream.enabled else 0}U, "
            f"{stream.decimation}U, {stream.period_us}UL,\n"
            f"     SSLOG_STREAM_POLICY_{stream.policy}}}"
        )
    body = ",\n".join(rows)
    return f"""#include "project_log_config.h"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

static const SystemLogStreamConfig s_project_log_streams[] =
{{
{body}
}};

_Static_assert((sizeof(s_project_log_streams) /
                sizeof(s_project_log_streams[0])) == SSLOG_RECORD_COUNT,
               "project log stream count mismatch");

uint16_t ProjectLogConfig_StreamCountGet(void)
{{
    return (uint16_t)(sizeof(s_project_log_streams) /
                      sizeof(s_project_log_streams[0]));
}}

const SystemLogStreamConfig *ProjectLogConfig_StreamByIndexGet(
    uint16_t index)
{{
    return (index < ProjectLogConfig_StreamCountGet()) ?
        &s_project_log_streams[index] : NULL;
}}
"""


def _MetadataSource_Render(model: ProjectModel, catalog: PluginCatalog) -> str:
    device_entries: list[dict[str, Any]] = []
    algorithm_entries: list[dict[str, Any]] = []
    for component_id in model.ComponentIds_Get():
        metadata = catalog.Component_Get(component_id).metadata
        device_entries.extend(metadata.get("device_descriptors", []))
        algorithm_entries.extend(metadata.get("algorithm_descriptors", []))
    device_entries.sort(key=lambda entry: int(entry["order"]))
    algorithm_entries.sort(key=lambda entry: int(entry["order"]))
    device_rows = []
    for descriptor_id, entry in enumerate(device_entries, start=1):
        device_rows.append(
            "    { "
            f"{descriptor_id}U, {entry['class']}, {int(entry.get('instance', 0))}U, "
            f"{int(entry.get('driver_id', 1))}U,\n"
            f"      {entry['flags']},\n"
            f"      {entry['capability']}, {entry['rate']},\n"
            f"      {entry['driver_hash']}, {entry['name_hash']} }}"
        )
    algorithm_rows = []
    for descriptor_id, entry in enumerate(algorithm_entries, start=1):
        algorithm_rows.append(
            "    { "
            f"{descriptor_id}U, {entry['class']}, {int(entry.get('instance', 0))}U,\n"
            f"      (uint16_t){entry['algorithm']},\n"
            f"      {entry['flags']},\n"
            f"      SILVERSTAR_PROJECT_CONFIG_DIGEST ^ 0x{descriptor_id:04X}0000UL, "
            f"{entry['name_hash']} }}"
        )
    digest = ProjectDigest_Get(model)
    return f"""#include "system_descriptor_if.h"

{AUTOGEN_C_COMMENT}

#include <stddef.h>

#include "system_capabilities.h"
#include "system_user_config.h"

#define SILVERSTAR_PROJECT_CONFIG_DIGEST 0x{digest:08X}UL

static const SystemDeviceDescriptor s_device_descriptors[] =
{{
{',\n'.join(device_rows)}
}};

static const SystemAlgorithmDescriptor s_algorithm_descriptors[] =
{{
{',\n'.join(algorithm_rows)}
}};

_Static_assert((sizeof(s_device_descriptors) /
                sizeof(s_device_descriptors[0])) <=
               SYSTEM_DESCRIPTOR_DEVICE_COUNT_MAX,
               "target device descriptor table exceeds interface bound");
_Static_assert((sizeof(s_algorithm_descriptors) /
                sizeof(s_algorithm_descriptors[0])) <=
               SYSTEM_DESCRIPTOR_ALGORITHM_COUNT_MAX,
               "target algorithm descriptor table exceeds interface bound");

uint16_t SystemDescriptor_DeviceCountGet(void)
{{
    return (uint16_t)(sizeof(s_device_descriptors) /
                      sizeof(s_device_descriptors[0]));
}}

SystemDeviceResult SystemDescriptor_DeviceGet(
    uint16_t index, SystemDeviceDescriptor *descriptor)
{{
    if ((descriptor == NULL) ||
        (index >= SystemDescriptor_DeviceCountGet()))
    {{
        return SYSTEM_DEVICE_INVALID_ARGUMENT;
    }}
    *descriptor = s_device_descriptors[index];
    return SYSTEM_DEVICE_OK;
}}

uint16_t SystemDescriptor_AlgorithmCountGet(void)
{{
    return (uint16_t)(sizeof(s_algorithm_descriptors) /
                      sizeof(s_algorithm_descriptors[0]));
}}

SystemDeviceResult SystemDescriptor_AlgorithmGet(
    uint16_t index, SystemAlgorithmDescriptor *descriptor)
{{
    if ((descriptor == NULL) ||
        (index >= SystemDescriptor_AlgorithmCountGet()))
    {{
        return SYSTEM_DEVICE_INVALID_ARGUMENT;
    }}
    *descriptor = s_algorithm_descriptors[index];
    return SYSTEM_DEVICE_OK;
}}

uint32_t SystemDescriptor_ConfigDigestGet(void)
{{
    return SILVERSTAR_PROJECT_CONFIG_DIGEST;
}}
"""


