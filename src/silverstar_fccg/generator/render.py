def _MakeSymbol_Get(value: str) -> str:
    return "_".join(
        part for part in re.split(r"[^A-Za-z0-9]+", value.upper()) if part
    )


def _TargetManifest_Render(
    model: ProjectModel, catalog: PluginCatalog, graph: SourceGraph
) -> str:
    flags = (" \\" + "\n" + "                    ").join(graph.mcu_flags)
    specs = " ".join(graph.specs)
    libraries = " ".join(graph.libraries)
    device_symbols = {
        catalog.Component_Get(component_id).component_class: _MakeSymbol_Get(
            catalog.Component_Get(component_id).name
        )
        for component_id in model.devices
    }
    platform_backend = _MakeSymbol_Get(
        catalog.Component_Get(model.mcu).component_class
    )
    board_profile = _MakeSymbol_Get(
        catalog.Component_Get(model.board).name
        if model.board
        else (model.hardware.source_label or "CUSTOM_STM32")
    )
    return f"""# AUTO-GENERATED BY SILVERSTAR_FCCG. DO NOT EDIT.
# Target flags are resolved from the selected MCU plugin.
BUILD_MANIFESTS += Targets/{model.build.target_profile}/target.mk

IMU_DRIVER := {device_symbols.get('imu', '')}
GNSS_DRIVER := {device_symbols.get('gnss', '')}
TELEMETRY_DRIVER := {device_symbols.get('telemetry', '')}
PLATFORM_BACKEND := {platform_backend}
BOARD_PROFILE := {board_profile}

TOOLCHAIN_PREFIX ?= {graph.toolchain_prefix}
TARGET_MCU_FLAGS := {flags}
TARGET_LDSCRIPT := {graph.linker_script}
TARGET_SPECS := {specs}
TARGET_LIBS := {libraries}
"""


def _VsCodeTasks_Render(model: ProjectModel) -> str:
    def task(label: str, args: list[str], matcher: Any = "$gcc", group: Any = None) -> dict[str, Any]:
        value: dict[str, Any] = {
            "label": label,
            "type": "shell",
            "command": model.build.tool_paths.get(
                "make", model.build.make_command
            ),
            "args": args,
            "problemMatcher": matcher,
        }
        if group is not None:
            value["group"] = group
        return value

    base = [
        f"TARGET_PROFILE={model.build.target_profile}",
        f"CONFIG={model.build.configuration}",
    ]
    tasks = [
        task(
            "SilverStar: Build",
            [*base, "all"],
            group={"kind": "build", "isDefault": True},
        ),
        task("SilverStar: Clean", [*base, "clean"], []),
        task("SilverStar: Host tests", ["host-tests"]),
        task("SilverStar: Architecture check", ["architecture-check"], []),
        task("SilverStar: Power of Ten check", ["power10-check"], []),
        task("SilverStar: Static analysis", [*base, "static-analysis"]),
        task("SilverStar: Artifact check", [*base, "artifact-check"]),
        task("SilverStar: Flash", [*base, "flash"]),
    ]
    return json.dumps({"version": "2.0.0", "tasks": tasks}, indent=4) + "\n"


