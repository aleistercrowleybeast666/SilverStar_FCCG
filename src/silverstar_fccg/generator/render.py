def ProjectDigest_Get(model: ProjectModel) -> int:
    data = model.Dictionary_Get()
    data["component_provenance"] = {}
    data["build"]["tool_paths"] = {}
    data["build"]["gcc_path"] = ""
    data["reference_provenance"] = {}
    canonical = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return zlib.crc32(canonical.encode("utf-8")) & 0xFFFFFFFF


def ComponentProvenance_Get(catalog: PluginCatalog, component_id: str) -> dict[str, Any]:
    manifest = catalog.Component_Get(component_id)
    digests: dict[str, str] = {}
    aggregate = hashlib.sha256()
    for path in manifest.PayloadFiles_Get():
        relative = path.relative_to(manifest.payload_root).as_posix()
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        digests[relative] = digest
        aggregate.update(relative.encode("utf-8"))
        aggregate.update(b"\0")
        aggregate.update(bytes.fromhex(digest))
    return {
        "version": manifest.version,
        "source": manifest.source,
        "manifest_id": manifest.component_id,
        "payload_digest": aggregate.hexdigest(),
        "files": digests,
    }


def GeneratedFiles_Render(
    model: ProjectModel, catalog: PluginCatalog, graph: SourceGraph
) -> dict[str, bytes]:
    files = {
        "Generated/project_sources.mk": graph.MakeFragment_Render(),
        "Generated/module.mk": _GeneratedModule_Render(),
        "Generated/Inc/project_log_config.h": _LogHeader_Render(),
        "Generated/Inc/project_resources.h": _ResourceHeader_Render(model, catalog),
        "Generated/Src/platform_resources.c": _PlatformResources_Render(model, catalog),
        "Generated/Src/project_log_config.c": _LogSource_Render(model),
        "Generated/Src/project_metadata.c": _MetadataSource_Render(model, catalog),
    }
    return {name: content.encode("utf-8") for name, content in files.items()}


def MetadataFiles_Render(
    model: ProjectModel, catalog: PluginCatalog, graph: SourceGraph
) -> dict[str, bytes]:
    environment = catalog.Component_Get(model.development_environment)
    if environment.environment is None or environment.environment.renderer != "vscode_eide_gcc":
        raise ValueError("Selected development environment has no trusted renderer")
    model.component_provenance = {
        component_id: ComponentProvenance_Get(catalog, component_id)
        for component_id in model.ComponentIds_Get()
    }
    project_json = json.dumps(
        model.Dictionary_Get(), ensure_ascii=False, indent=2, sort_keys=False
    ) + "\n"
    files = {
        "SilverStar.ssproject": project_json,
        "SilverStar_Configuration.md": _Configuration_Render(model, catalog, graph),
        "Makefile": _Makefile_Render(model),
        f"Targets/{model.build.target_profile}/target.mk": _TargetManifest_Render(
            model, catalog, graph
        ),
        ".vscode/tasks.json": _VsCodeTasks_Render(model),
        ".vscode/settings.json": _VsCodeSettings_Render(),
        ".vscode/extensions.json": _VsCodeExtensions_Render(),
        ".eide/eide.yml": _Eide_Render(model, graph),
        ".eide/files.options.yml": _EideFileOptions_Render(),
        f"{model.identity.name}.code-workspace": _VsCodeWorkspace_Render(model),
        "README.md": _GeneratedReadme_Render(model),
    }
    return {name: content.encode("utf-8") for name, content in files.items()}


