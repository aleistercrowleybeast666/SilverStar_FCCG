def _Configuration_Render(model: ProjectModel, catalog: PluginCatalog, graph: SourceGraph) -> str:
    lines = [
        f"# {model.identity.name} Configuration",
        "",
        "> AUTO-GENERATED BY SILVERSTAR_FCCG. This human-readable file may be overwritten.",
        "",
        f"- Firmware: `{model.identity.firmware_version}`",
        f"- Build target: `{model.identity.build_target}`",
        f"- Target profile: `{model.build.target_profile}`",
        f"- Configuration: `{model.build.configuration}`",
        f"- Toolchain prefix: `{graph.toolchain_prefix}`",
        f"- MCU: `{model.mcu}`",
        f"- Board: `{model.board or 'custom hardware'}`",
        f"- Hardware source: `{model.hardware.source_kind}` / `{model.hardware.mode}`",
        f"- Development environment: `{model.development_environment}`",
        f"- Authoritative source graph: `Generated/project_sources.mk`",
        f"- EIDE mode: `{model.build.eide_mode}`",
        "",
        "## Components",
        "",
    ]
    for component_id in model.ComponentIds_Get():
        manifest = catalog.Component_Get(component_id)
        lines.append(
            f"- `{manifest.component_type}` / `{manifest.component_class or 'default'}`: "
            f"{manifest.name} `{manifest.version}` (`{component_id}`)"
        )
    lines.extend(("", "## Strategies", ""))
    for slot, component_id in sorted(model.strategies.items()):
        lines.append(f"- `{slot}`: `{component_id or 'None'}`")
    lines.extend(("", "## Modes", ""))
    for slot, selections in sorted(model.modes.items()):
        lines.append(f"- `{slot}`: `{', '.join(selections) if selections else '[]'}`")
    lines.extend(("", "## Resource mapping", ""))
    for key, value in sorted(model.resource_assignments.items()):
        lines.append(f"- `{key}` → `{value}`")
    lines.extend(("", "## SSLOG streams", ""))
    for stream in model.logging_streams:
        state = "enabled" if stream.enabled else "disabled"
        lines.append(
            f"- `{stream.record}`: {state}, `{stream.policy}`, "
            f"decimation={stream.decimation}, period_us={stream.period_us}"
        )
    lines.extend(("", "## Hardware provenance", ""))
    if model.hardware.mode == "custom":
        lines.extend(
            (
                f"- Provider: `{model.hardware.provider}`",
                f"- Imported project: `{model.hardware.source_label}`",
                f"- IOC: `{model.hardware.ioc_file}`",
                f"- Imported MCU: `{model.hardware.mcu}`",
                f"- Snapshot digest: `{model.hardware.source_digest}`",
                "- Verification: custom hardware; not an official SilverStar hardware verification claim",
            )
        )
    else:
        board = catalog.Component_Get(model.board)
        lines.extend(
            (
                f"- Board source kind: `{board.board.source_kind if board.board else 'unknown'}`",
                f"- Verified: `{bool(board.board and board.board.verified)}`",
            )
        )
    lines.extend(("", "## Reference provenance", ""))
    for key, value in sorted(model.reference_provenance.items()):
        lines.append(f"- `{key}`: `{value}`")
    lines.extend(
        (
            "",
            "## Resolved source graph",
            "",
            f"- C sources: `{len(graph.sources)}`",
            f"- Assembler sources: `{len(graph.asm_sources)}`",
            f"- Include directories: `{len(graph.include_dirs)}`",
            f"- Linker script: `{graph.linker_script}`",
        )
    )
    lines.extend(
        (
            "",
            "## Ownership",
            "",
            "Component payloads are project-owned after first copy and are not overwritten by normal Apply.",
            "Only `Generated/` glue and FCCG project/build metadata are normally regenerated by FCCG.",
            "`HardwareGenerated/` is vendor-owned data and is replaced only after an explicit re-import confirmation.",
            "",
        )
    )
    return "\n".join(lines)


